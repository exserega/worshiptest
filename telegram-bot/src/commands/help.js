// =====================================================

/**
 * Обработчик команды /help
 */
async function handleHelp(bot, msg) {
    const chatId = msg.chat.id;

    const helpMessage = 
        `📚 **Справка по командам**\n\n` +
        
        `**Основные команды:**\n` +
        `/start - Главное меню\n` +
        `/help - Эта справка\n\n` +
        
        `**Поиск:**\n` +
        `/song [название] - Поиск песни\n` +
        `Пример: \`/song Благая весть\`\n\n` +
        
        `**События:**\n` +
        `/events - Список ближайших служений\n\n` +
        
        `**Быстрый доступ:**\n` +
        `🎵 Кнопка "Открыть Agape Worship" - запуск полного приложения\n\n` +
        
        `**Дополнительно:**\n` +
        `• Просто напишите название песни - я помогу найти её\n` +
        `• Используйте кнопки меню для быстрой навигации\n\n` +
        
        `❓ Возникли проблемы?\n` +
        `Попробуйте перезапустить бота командой /start`;

    try {
        await bot.sendMessage(chatId, helpMessage, {
            parse_mode: 'Markdown',
            reply_markup: {
                inline_keyboard: [[
                    {
                        text: '🎵 Открыть Agape Worship',
                        web_app: { url: process.env.WEB_APP_URL }
                    }
                ]]
            }
        });
    } catch (error) {
        console.error('❌ Ошибка в команде /help:', error);
        await bot.sendMessage(chatId, '❌ Произошла ошибка при отображении справки');
    }
}

module.exports = { handleHelp };
